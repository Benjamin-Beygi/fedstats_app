# 7.  Logistic regression: patient satisfaction at 12 months
# =====================================================================
cat("\n----- Logistic regression: patient_satisfied_12m -----\n")

logit_sat <- fed_logistic_newton(
  servers,
  patient_satisfied_12m ~ age + sexM + bmi + smoker +
    nrs_arm_preop + ndi_index_preop + diag_myelo +
    comorbid_cardiac + opioids_preop + nrs_arm_12m,
  robust_cluster = TRUE,
  verbose        = FALSE
)

.se_sat <- if (!is.null(logit_sat$se_robust)) logit_sat$se_robust else logit_sat$se
.b_sat  <- logit_sat$coefficients
.z_sat  <- .b_sat / .se_sat
.p_sat  <- 2 * (1 - pnorm(abs(.z_sat)))

logit_sat_tab <- data.frame(
  Term      = names(.b_sat),
  Estimate  = round(.b_sat,                     4),
  Std.Error = round(.se_sat,                    4),
  z.value   = round(.z_sat,                     3),
  p.value   = round(.p_sat,                     4),
  OR        = round(exp(.b_sat),               4),
  CI.lower  = round(exp(.b_sat - 1.96 * .se_sat), 4),
  CI.upper  = round(exp(.b_sat + 1.96 * .se_sat), 4),
  stringsAsFactors = FALSE
)
rownames(logit_sat_tab) <- NULL

register_output("Table 6 — Logistic (satisfaction)", logit_sat_tab, "table",
                sprintf(
                  "Logistic: patient_satisfied_12m ~ 10 predictors | N = %d, logLik = %.3f%s",
                  logit_sat$N, logit_sat$logLik,
                  if (!is.null(logit_sat$clusters))
                    sprintf(", cluster-robust SE (%d sites)", logit_sat$clusters) else ""
                ))

