cat("\n----- Chi-square: binary outcomes by diagnosis -----\n")

.chisq_items <- list(
  list(x = "sexM",               label = "Male sex"),
  list(x = "smoker",             label = "Smoker"),
  list(x = "comorbid_cardiac",   label = "Cardiac comorbidity"),
  list(x = "opioids_preop",      label = "Opioid use preop"),
  list(x = "mcid_arm_12m",       label = "MCID arm 12m"),
  list(x = "mcid_eq5d_12m",      label = "MCID EQ-5D 12m"),
  list(x = "patient_satisfied_12m", label = "Patient satisfied 12m"),
  list(x = "any_complication",   label = "Any complication"),
  list(x = "reoperated",         label = "Reoperated")
)

chisq_rows <- lapply(.chisq_items, function(item) {
  res <- tryCatch(
    fed_chisq_2x2(servers, item$x, "diag_myelo", correct = TRUE),
    error = function(e) NULL
  )
  if (is.null(res)) {
    return(data.frame(Variable = item$label, X2 = NA, df = NA,
                      p = NA, N = NA, stringsAsFactors = FALSE))
  }
  data.frame(
    Variable = item$label,
    X2 = round(res$statistic, 3),
    df = res$df,
    p  = round(res$p, 4),
    N  = res$N,
    stringsAsFactors = FALSE
  )
})

chisq_tab <- do.call(rbind, chisq_rows)
register_output("Table 4 — Chi-square", chisq_tab, "table",
                "Chi-square (Yates correction): binary variables by diagnosis group")

