# 9.  Forest plot: patient satisfaction logistic regression
# =====================================================================
register_output(
  name  = "Forest plot — Satisfaction",
  value = local({
    .lt <- logit_sat_tab
    function() {
      .rows <- .lt[.lt$Term != "(Intercept)", ]
      .n    <- nrow(.rows)
      if (.n == 0) { plot.new(); text(0.5, 0.5, "No predictors."); return() }
      .y_pos <- seq(.n, 1)
      .x_lo  <- max(0.05, min(.rows$CI.lower, na.rm = TRUE) * 0.75)
      .x_hi  <- max(.rows$CI.upper, na.rm = TRUE) * 1.40
      .old   <- par(mar = c(4.5, 10, 3.5, 2.5))
      on.exit(par(.old), add = TRUE)
      plot(.rows$OR, .y_pos,
           xlim = c(.x_lo, .x_hi), ylim = c(0.3, .n + 0.7),
           xlab = "Odds ratio (95% CI)", ylab = "",
           yaxt = "n", log = "x", pch = 15, cex = 1.4, col = "#2b6cb0",
           main = "Patient satisfaction at 12 months")
      for (.i in seq_len(.n))
        lines(c(.rows$CI.lower[.i], .rows$CI.upper[.i]),
              c(.y_pos[.i], .y_pos[.i]), col = "#2b6cb0", lwd = 2)
      abline(v = 1, lty = 2, col = "grey60")
      axis(2, at = .y_pos, labels = .rows$Term, las = 1, cex.axis = 0.85)
      for (.i in seq_len(.n))
        text(.rows$OR[.i], .y_pos[.i] + 0.38,
             labels = sprintf("%.2f [%.2f–%.2f]",
                              .rows$OR[.i], .rows$CI.lower[.i], .rows$CI.upper[.i]),
             cex = 0.72, col = "#2b6cb0")
    }
  }),
  type    = "plot",
  caption = "Odds ratios (95% CI) for patient satisfaction at 12 months — logistic regression"
)

