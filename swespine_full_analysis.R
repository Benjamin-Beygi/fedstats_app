    "Myelopathy (mean±SD)"    = sprintf("%.2f ± %.2f (n=%d)",
                                         tt$mean2, tt$sd2, tt$n2),
    t      = round(tt$t,  3),
    df     = round(tt$df, 1),
    p      = round(tt$p,  4),
    check.names = FALSE, stringsAsFactors = FALSE
  )
})

