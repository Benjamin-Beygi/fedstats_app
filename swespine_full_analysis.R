ttest_rows <- lapply(.ttests, function(item) {
  tt <- fed_welch_t(servers, item$var, "diag_grp",
                    "radiculopathy", "myelopathy")
  data.frame(
    Outcome        = item$label,
    "Radiculopathy (mean±SD)" = sprintf("%.2f ± %.2f (n=%d)",
